# Методы списков и строк. Задача 11
n = int(input())

for _ in range(n):
    nums = list(map(int, input().split()))
    
    # Чтобы из чисел можно было построить строго убывающую последовательность,
    # все числа должны быть различны (никакие два не равны),
    # и тогда их можно просто отсортировать по убыванию.
    # Если есть повторы — строго убывающую построить нельзя.
    
    if len(nums) == len(set(nums)):
        print("ДА")
    else:
        print("НЕТ")
